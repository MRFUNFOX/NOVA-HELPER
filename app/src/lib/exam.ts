/** Сослался ли ответ на нужный пункт: «4.1» не должен совпадать с «4.10» */
export function citesRef(labels: string[], refs: string[]) {
  return refs.some((r) => {
    const re = new RegExp(`(^|[^\\d.])${r.replace(/\./g, '\\.')}(?![\\d]|\\.\\d)`);
    return labels.some((l) => re.test(l));
  });
}

export type Match = 'yes' | 'partly' | 'no';
export interface ExamResult {
  id: string;
  answer: string;
  /** Подписи пунктов, на которые сослался ответ: «4.1 · Общие правила проекта» */
  cited: string[];
  citedOk: boolean;
  match: Match | 'error';
  why: string;
  model?: string;
  seconds?: number;
  /** Ответ поправила самопроверка */
  fixed?: boolean;
}

/** Итог: «да» — 1 балл, «частично» — половина */
export function examScore(rs: ExamResult[]) {
  if (!rs.length) return 0;
  const pts = rs.reduce((s, r) => s + (r.match === 'yes' ? 1 : r.match === 'partly' ? 0.5 : 0), 0);
  return Math.round((pts / rs.length) * 100);
}

