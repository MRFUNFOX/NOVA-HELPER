/** Сослался ли ответ на нужный пункт: «4.1» не должен совпадать с «4.10» */
export function citesRef(labels: string[], refs: string[]) {
  return refs.some((r) => {
    const re = new RegExp(`(^|[^\\d.])${r.replace(/\./g, '\\.')}(?![\\d]|\\.\\d)`);
    return labels.some((l) => re.test(l));
  });
}

export type Match = 'yes' | 'partly' | 'no';
/** stale — правило, на котором держится эталон, изменилось: вопрос не оценивается, эталон надо переписать */
export interface ExamResult {
  id: string;
  answer: string;
  /** Подписи пунктов, на которые сослался ответ: «4.1 · Общие правила проекта» */
  cited: string[];
  citedOk: boolean;
  match: Match | 'error' | 'stale';
  why: string;
  model?: string;
  seconds?: number;
  /** Ответ поправила самопроверка */
  fixed?: boolean;
}

/** Итог: «да» — 1 балл, «частично» — половина. Вопросы с устаревшим эталоном в итог не входят */
export function examScore(rs: ExamResult[]) {
  const counted = rs.filter((r) => r.match !== 'stale');
  if (!counted.length) return 0;
  const pts = counted.reduce((s, r) => s + (r.match === 'yes' ? 1 : r.match === 'partly' ? 0.5 : 0), 0);
  return Math.round((pts / counted.length) * 100);
}

/** Какие опоры эталона не нашлись в нынешних правилах: пункта нет или в нём нет нужных слов.
 *  `texts(ref)` — тексты пунктов с этим номером в разделе вопроса (с наказаниями). */
export function staleRules(item: ExamItem, texts: (ref: string) => string[]): string[] {
  const norm = (t: string) => t.toLowerCase().replace(/ё/g, 'е').replace(/\s+/g, ' ');
  return item.rule.filter(([ref, has]) => !texts(ref).some((t) => norm(t).includes(norm(has)))).map(([ref]) => ref);
}

