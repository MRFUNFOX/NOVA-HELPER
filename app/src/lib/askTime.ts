// Окно ответа на вопрос голосом в игре: отдельный маленький файл, чтобы окно не тянуло за собой помощника и правила

/** Сколько секунд показывать ответ в режиме «Авто»: 8 с заметить + 0,9 с на слово ответа + 0,3 с на слово вопроса, от 15 до 60 с */
export function autoSeconds(answerWords: number, questionWords = 0) {
  return Math.min(60, Math.max(15, 8 + answerWords * 0.9 + questionWords * 0.3));
}
