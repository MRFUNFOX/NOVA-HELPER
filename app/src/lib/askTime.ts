// Окно ответа на вопрос голосом в игре: отдельный маленький файл, чтобы окно не тянуло за собой помощника и правила

/** Сколько секунд показывать ответ в режиме «Авто»: 15 с заметить + 1,5 с на слово ответа + 0,4 с на слово вопроса,
 *  от 30 секунд до 2 минут (решение владельца 25.11: лучше дольше — убрать можно и самому, через меню) */
export function autoSeconds(answerWords: number, questionWords = 0) {
  return Math.round(Math.min(120, Math.max(30, 15 + answerWords * 1.5 + questionWords * 0.4)));
}
