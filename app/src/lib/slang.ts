/** Разговорные слова игроков → как это написано в правилах (для поиска без помощи нейросети) */
const W = '(?<!\\p{L})';
const E = '(?!\\p{L})';
const re = (src: string) => new RegExp(src.replaceAll('<', W).replaceAll('>', E), 'iu');
const SLANG: [RegExp, string][] = [
  [re('<(растул\\p{L}*|завал(ил|или|ю|им)>|полож(ил|или|ат|у)>|уби(л|ли|ть|вать|йство)|убь|грохн\\p{L}*|замочи\\p{L}*|кильн\\p{L}*|килл\\p{L}*|kill)'), 'убийство DM DeathMatch'],
  [re('<(коп(а|у|ом|ы|ов|ам)?>|мент\\p{L}{0,3}>|полиц\\p{L}*|lspd|lssd|шериф\\p{L}*)'), 'сотрудник полиции LSPD'],
  [re('<(о?граб\\p{L}*)'), 'ограбление'],
  [re('<(похит\\p{L}*|похищ\\p{L}*|кидна\\p{L}*)'), 'похищение'],
  [re('<(таран\\p{L}*|сбил\\p{L}{0,2}>|задавил\\p{L}*|переех\\p{L}*)'), 'DB DriveBy транспорт'],
  [re('<(мест(ь|и)>|отомст\\p{L}*)'), 'RevengeKill RK'],
  [re('<(оскорб\\p{L}*|материл\\p{L}*|мамк\\p{L}*|родн(ых|ые|ым)>)'), 'оскорбление родных'],
  [re('<(машин\\p{L}*|тачк\\p{L}*|авто>|угон\\p{L}*|угнал\\p{L}*)'), 'транспорт угон'],
  [re('<(зел[её]н\\p{L}*)'), 'зелёная зона'],
  [re('<(читер\\p{L}*|чит(ы|ом|ами|ов)?>|баг(и|ом|ами|ов)?>|багоюз\\p{L}*)'), 'читы баги'],
];
export function slang(text: string) {
  return SLANG.filter(([re]) => re.test(text)).map(([, w]) => w).join(' ');
}

